from typing import Protocol
from ..contracts.asset_library import BrainAssetView
from ..contracts.asset_catalog import AssetCatalogSnapshot


class AssetLibraryPort(Protocol):
    def resolve(self, metadata_ref: str, asset_type: str | None = None) -> BrainAssetView: ...
    def find_by_name(self, semantic_name: str) -> list[BrainAssetView]: ...
    def find_by_category(self, category: str) -> list[BrainAssetView]: ...
    def catalog_snapshot(self, *, aliases: dict[str, str] | None = None,
                        registered_profiles: list[str] | None = None) -> AssetCatalogSnapshot: ...
